// Writes docs/noah/FILES.md: every frontend source file the app needs, in dependency order (a file appears after
// everything it imports), each with its path and full content, plus the exact package.json dependencies. It is the
// paste-in fallback for porting MuchTip into Noah AI if Noah cannot import a repository (docs/noah-research.md).
//
//   node scripts/noah-kit.mjs        (from frontend/)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.resolve(ROOT, "../docs/noah/FILES.md");
const rel = (p) => path.relative(ROOT, p).replace(/\\/g, "/");

// Source files reachable from the entry point, following relative imports (tests are never imported, so never included).
const graph = new Map();
function visit(file) {
  if (graph.has(file)) return;
  const src = fs.readFileSync(file, "utf8");
  const deps = [];
  graph.set(file, deps);
  for (const m of src.matchAll(/(?:import|export)\s[^"']*?from\s*["'](\.{1,2}\/[^"']+)["']|import\(\s*["'](\.{1,2}\/[^"']+)["']\s*\)|import\s+["'](\.{1,2}\/[^"']+)["']/g)) {
    const spec = m[1] ?? m[2] ?? m[3];
    const base = path.resolve(path.dirname(file), spec.replace(/\?raw$/, ""));
    const hit = [base, `${base}.ts`, `${base}.tsx`, path.join(base, "index.ts"), path.join(base, "index.tsx")].find((f) => fs.existsSync(f) && fs.statSync(f).isFile());
    if (!hit) throw new Error(`cannot resolve ${spec} from ${rel(file)}`);
    if (!hit.startsWith(path.join(ROOT, "src"))) continue; // e.g. ../../../deployment.json is only used by tests
    deps.push(hit);
    visit(hit);
  }
}
visit(path.join(ROOT, "src/main.tsx"));

// Leaves first: a file is listed after everything it imports.
const order = [];
const done = new Set();
const place = (f) => {
  if (done.has(f)) return;
  done.add(f);
  for (const d of graph.get(f)) place(d);
  order.push(f);
};
[...graph.keys()].sort().forEach(place);

const config = ["package.json", "index.html", "vite.config.ts", "tsconfig.json", "tailwind.config.ts", "postcss.config.js", "public/favicon.svg", "src/vite-env.d.ts", "scripts/secret-scan.mjs", "scripts/secret-scan-allow.txt"].map((f) => path.join(ROOT, f));
const lang = (f) => ({ ".ts": "ts", ".tsx": "tsx", ".css": "css", ".json": "json", ".html": "html", ".js": "js", ".mjs": "js", ".svg": "svg", ".txt": "text" })[path.extname(f)] ?? "";
const fence = (body) => (body.includes("```") ? "````" : "```");

const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
const block = (f) => {
  const body = fs.readFileSync(f, "utf8").replace(/\r\n/g, "\n").replace(/\n$/, "");
  const fe = fence(body);
  return `### \`${rel(f)}\`\n\n${fe}${lang(f)}\n${body}\n${fe}\n`;
};

const lines = [
  "# MuchTip frontend files (paste-in kit for Noah AI)",
  "",
  `Generated by \`frontend/scripts/noah-kit.mjs\` from the repository. Regenerate after any frontend change; do not edit by hand.`,
  "",
  "Paste each file into the Noah project at the same path, **in the order below**: every file comes after the files it",
  "imports, so the project compiles at each step. Paths are relative to the project root (the folder with `package.json`).",
  "",
  "## Dependencies (exact versions)",
  "",
  "These are pinned in `package.json` below. If Noah manages packages itself, install exactly these:",
  "",
  "| Package | Version | |",
  "|---|---|---|",
  ...Object.entries(pkg.dependencies).map(([n, v]) => `| \`${n}\` | ${v} | runtime |`),
  ...Object.entries(pkg.devDependencies)
    .filter(([n]) => ["vite", "@vitejs/plugin-react", "tailwindcss", "postcss", "autoprefixer", "typescript", "@types/react", "@types/react-dom", "@types/node"].includes(n))
    .map(([n, v]) => `| \`${n}\` | ${v} | build |`),
  "",
  "Test and lint tools (vitest, eslint, Testing Library, jsdom) are only needed to run `npm run check` and are left out",
  "of the paste list; `package.json` still lists them.",
  "",
  `## Configuration and entry files (${config.length})`,
  "",
  ...config.map(block),
  `## Source files in dependency order (${order.length})`,
  "",
  ...order.map((f, i) => `${i + 1}. \`${rel(f)}\``),
  "",
  ...order.map(block),
];
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join("\n"));
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${config.length} config files + ${order.length} source files`);
